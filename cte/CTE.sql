-- CTE Example: Employee hierarchy
WITH RECURSIVE EMPLOYEE_HIERARCHY AS (
    -- ANCHOR MEMBER: Top level managers (no manager)
    SELECT
        EMPLOYEE_ID,
        FIRST_NAME,
        LAST_NAME,
        MANAGER_ID,
        1 AS HIERARCHY_LEVEL,
        CONCAT(FIRST_NAME, ' ', LAST_NAME) AS PATH
    FROM EMPLOYEES
    WHERE MANAGER_ID IS NULL

    UNION ALL

    -- RECURSIVE MEMBER: Employees with managers
    SELECT
        E.EMPLOYEE_ID,
        E.FIRST_NAME,
        E.LAST_NAME,
        E.MANAGER_ID,
        H.HIERARCHY_LEVEL + 1,
        CONCAT(H.PATH, ' -> ', E.FIRST_NAME, ' ', E.LAST_NAME)
    FROM EMPLOYEES E
             INNER JOIN EMPLOYEE_HIERARCHY H ON E.MANAGER_ID = H.EMPLOYEE_ID
)
SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    LAST_NAME,
    HIERARCHY_LEVEL,
    PATH
FROM EMPLOYEE_HIERARCHY
ORDER BY PATH;


-- Without CTE (Standard SQL - using self-joins for fixed levels)
-- Note: This only works for a fixed number of levels
SELECT
    E1.EMPLOYEE_ID,
    E1.FIRST_NAME,
    E1.LAST_NAME,
    CASE
        WHEN E1.MANAGER_ID IS NULL THEN 1
        WHEN E2.MANAGER_ID IS NULL THEN 2
        WHEN E3.MANAGER_ID IS NULL THEN 3
        ELSE 4
        END AS HIERARCHY_LEVEL,
    CONCAT(
            COALESCE(CONCAT(E3.FIRST_NAME, ' ', E3.LAST_NAME, ' -> '), ''),
            COALESCE(CONCAT(E2.FIRST_NAME, ' ', E2.LAST_NAME, ' -> '), ''),
            COALESCE(CONCAT(E1.FIRST_NAME, ' ', E1.LAST_NAME), '')
    ) AS PATH
FROM EMPLOYEES E1
         LEFT JOIN EMPLOYEES E2 ON E1.MANAGER_ID = E2.EMPLOYEE_ID
         LEFT JOIN EMPLOYEES E3 ON E2.MANAGER_ID = E3.EMPLOYEE_ID
ORDER BY
    COALESCE(E3.EMPLOYEE_ID, E2.EMPLOYEE_ID, E1.EMPLOYEE_ID),
    E2.EMPLOYEE_ID,
    E1.EMPLOYEE_ID;